  studio_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  studio_name FitServe.studio_name_enum NOT NULL UNIQUE,
  max_capacity INTEGER NOT NULL CHECK (max_capacity > 0),
  studio_status BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE FitServe.studio_type ( -- lily
  studio_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  activity_name VARCHAR(50) NOT NULL CHECK (TRIM(activity_name) <> ''),
  studio_id INTEGER NOT NULL,

  UNIQUE (studio_id, activity_name),
  FOREIGN KEY (studio_id) REFERENCES FitServe.studios(studio_id)
    ON DELETE CASCADE
    ON UPDATE CASCADE
);

CREATE TABLE FitServe.session ( -- lily
  session_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  time_start TIMESTAMP NOT NULL,
  time_end TIMESTAMP NOT NULL,
  booking FitServe.booking_status_enum NOT NULL DEFAULT 'planned',
  studio_id INTEGER,

  CHECK (time_end > time_start),
  CHECK (time_end <= time_start + INTERVAL '3 hours'),
  FOREIGN KEY (studio_id) REFERENCES FitServe.studios(studio_id)
    ON DELETE SET NULL
    ON UPDATE CASCADE
);

CREATE TABLE FitServe.athlete_session ( -- lily
  athlete_session_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  session_id INTEGER NOT NULL,
  athlete_id INTEGER NOT NULL,

  UNIQUE (session_id, athlete_id),
  FOREIGN KEY (session_id) REFERENCES FitServe.session(session_id)
    ON DELETE CASCADE
    ON UPDATE CASCADE,
  FOREIGN KEY (athlete_id) REFERENCES FitServe.athletes(athlete_id)
    ON DELETE CASCADE
    ON UPDATE CASCADE
);

