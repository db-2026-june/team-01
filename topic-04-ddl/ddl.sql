  FOREIGN KEY (trainer_id) REFERENCES FitServe.trainers(trainer_id)
    ON DELETE CASCADE
    ON UPDATE CASCADE,
  FOREIGN KEY (session_id) REFERENCES FitServe.session(session_id)
    ON DELETE CASCADE
    ON UPDATE CASCADE
